def project_spec(spec: dict[str, Any], *, project: Any = None, method_id: str | None = None) -> dict[str, Any]:
    from . import __version__

    data_path = None
    if project is not None:
        try:
            data_path = str(project.parquet_path)
        except Exception:
            data_path = None
    notes: list[str] = []
    missing_r = [
        m["method_id"] for m in _methods_of(spec, method_id) if m["method_id"] not in _R_SNIPPETS
    ]
    if missing_r:
        notes.append(
            "No R projection yet for: " + ", ".join(sorted(set(missing_r)))
            + ". The Python projection reproduces the run exactly."
        )
    return {
        "yaml": spec_yaml(spec),
        "python": python_script(spec, method_id=method_id, version=__version__, data_path=data_path),
        "r": r_script(spec, method_id=method_id, version=__version__, data_path=data_path),
        "notes": notes,
        "data_path": data_path,
    }
