"""Three projections of one spec: YAML, R, Python.

Gretl's command log is one of its best ideas, and we keep the spirit -- but the
spec is the source of truth and the scripts are generated from it. A hand-edited
script forks into a "custom" analysis that must still return the canonical
result schema.
"""

from __future__ import annotations

import json
from pprint import pformat
from typing import Any

import yaml

HEADER = """# Generated by Causal Capybara {version}.
# This script is a projection of the study spec, not the other way round.
# Editing it forks the analysis: a custom script must still return a
# capy.result.v1 record before it can enter a comparison.
"""


def spec_yaml(spec: dict[str, Any]) -> str:
    return yaml.safe_dump(_clean(spec), sort_keys=False, allow_unicode=True)


def _clean(obj: Any) -> Any:
    if isinstance(obj, dict):
        return {k: _clean(v) for k, v in obj.items() if v not in (None, [], {}) or k in ("cutoff",)}
    if isinstance(obj, list):
        return [_clean(v) for v in obj]
    return obj


def _r_str(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "c(" + ", ".join(_r_str(v) for v in value) + ")"
    return json.dumps(str(value))


def _r_formula(outcome: str, terms: list[str]) -> str:
    rhs = " + ".join(terms) if terms else "1"
    return f"{outcome} ~ {rhs}"


def _r_name(value: str) -> str:
    """Quote a column identifier separately from an R character literal."""
    return "`" + str(value).replace("\\", "\\\\").replace("`", "\\`") + "`"


# ---------------------------------------------------------------------------
# Python projection -- runs through the same adapters the GUI runs
# ---------------------------------------------------------------------------


def python_script(spec: dict[str, Any], *, method_id: str | None = None, version: str = "0.1.0",
                  data_path: str | None = None) -> str:
    methods = _methods_of(spec, method_id)
    body = [
        HEADER.format(version=version),
        "import json",
        "import pandas as pd",
        "from capy_py.contracts import run_method",
        "",
        f"DATA = {json.dumps(data_path or 'data/analysis.parquet')}",
        f"SEED = {int(spec['seed'] if spec.get('seed') is not None else 20260830)}",
        "",
        "SPEC = " + _py_literal(_clean(spec)),
        "",
        "df = pd.read_parquet(DATA)",
        "",
        "for method_id, options in [",
    ]
    for m in methods:
        body.append(f"    ({json.dumps(m['method_id'])}, {_py_literal(m.get('options') or {})}),")
    body += [
        "]:",
        "    result = run_method(method_id, SPEC, df, seed=SEED, options=options)",
        "    print(result['method_label'], result['estimate'], result['ci_low'], result['ci_high'])",
        "    with open(f\"{result['run_id']}.json\", 'w', encoding='utf-8') as fh:",
        "        json.dump(result, fh, indent=2)",
        "",
    ]
    return "\n".join(body)


def _py_literal(obj: Any, indent: int = 0) -> str:
    # Python syntax must be produced structurally: replacing JSON tokens in
    # strings can change variable names and leaves nested boolean lists invalid.
    text = pformat(obj, width=88, sort_dicts=False)
    if indent:
        pad = " " * indent
        text = "\n".join(pad + line if i else line for i, line in enumerate(text.splitlines()))
    return text


