def _methods_of(spec: dict[str, Any], method_id: str | None) -> list[dict[str, Any]]:
    if method_id:
        for m in spec.get("methods") or []:
            if m.get("method_id") == method_id:
                return [m]
        return [{"method_id": method_id, "options": {}}]
    chosen = [m for m in (spec.get("methods") or []) if m.get("included", True)]
    return chosen or [{"method_id": "obs.outcome_regression", "options": {}}]


