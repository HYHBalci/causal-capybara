def r_script(spec: dict[str, Any], *, method_id: str | None = None, version: str = "0.1.0",
             data_path: str | None = None) -> str:
    roles = spec.get("roles") or {}
    methods = _methods_of(spec, method_id)
    lines = [
        HEADER.format(version=version).replace("#", "#", 1),
        '# R reference calculations use the packages and inference stated below.',
        '# Use the Python projection for exact replay of a Python-engine run, including',
        '# its sample handling, diagnostics, resampling and method options.',
        'library(arrow)',
        "",
        f'data_path <- {json.dumps(data_path or "data/analysis.parquet")}',
        f"set.seed({int(spec['seed'] if spec.get('seed') is not None else 20260830)})",
        "d <- as.data.frame(arrow::read_parquet(data_path))",
        "",
    ]
    subset = ((spec.get("sample") or {}).get("subset_expr"))
    if subset:
        lines.append(f"# population filter, exactly as recorded in the spec")
        lines.append(f"d <- subset(d, {subset})")
        lines.append("")
    for m in methods:
        snippet = _R_SNIPPETS.get(m["method_id"])
        lines.append(f"## {m['method_id']}")
        if snippet is None:
            lines.append(
                f"# No R projection for {m['method_id']} yet. The Python engine ran this one;\n"
                f"# see the Code tab's Python projection, or fork a custom R script that returns\n"
                f"# a capy.result.v1 record."
            )
        else:
            try:
                lines.append(snippet(roles, m.get("options") or {}, spec))
            except Exception as exc:  # a bad projection must not break the tab
                lines.append(f"# Could not project this method to R: {exc}")
        lines.append("")
    return "\n".join(lines)


def _confounders(roles: dict[str, Any]) -> list[str]:
    forbidden = set(roles.get("forbidden") or [])
    return [c for c in (roles.get("confounders") or []) if c not in forbidden]


def _s_outcome_reg(roles, opts, spec) -> str:
    y, d = roles.get("outcome"), roles.get("treatment")
    x = _confounders(roles)
    return (
        "library(marginaleffects)\n"
        f"fit <- lm({_r_formula(y, [d] + x)}, data = d)\n"
        f"avg_comparisons(fit, variables = {_r_str(d)},\n"
        f"                newdata = {'subset(d, ' + d + ' == 1)' if (spec.get('estimand') == 'ATT') else 'd'})"
    )


